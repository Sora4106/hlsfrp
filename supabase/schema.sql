create or replace function public.hls_is_admin()
returns boolean
language sql
stable
security definer
set search_path = public
as $$
  select exists (
    select 1 from public.hls_admins where user_id = auth.uid()
  );
$$;

create or replace function public.hls_get_site_content()
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select jsonb_build_object(
    'categories', coalesce((
      select jsonb_agg(to_jsonb(item) - 'created_at' - 'updated_at' - 'published' order by item.sort_order, item.id)
      from public.hls_product_categories item where item.published
    ), '[]'::jsonb),
    'products', coalesce((
      select jsonb_agg(to_jsonb(item) - 'created_at' - 'updated_at' - 'published' order by item.sort_order, item.id)
      from public.hls_products item where item.published
    ), '[]'::jsonb),
    'news', coalesce((
      select jsonb_agg(to_jsonb(item) - 'created_at' - 'updated_at' - 'published' order by item.published_at desc, item.id desc)
      from public.hls_news item where item.published
    ), '[]'::jsonb),
    'locations', coalesce((
      select jsonb_agg(to_jsonb(item) - 'created_at' - 'updated_at' - 'published' order by item.sort_order, item.id)
      from public.hls_locations item where item.published
    ), '[]'::jsonb)
  );
$$;

create or replace function public.hls_get_media_usage(p_url text)
returns jsonb
language sql
stable
security definer
set search_path = public
as $$
  select case when public.hls_is_admin() then jsonb_build_object(
    'categories', (select count(*) from public.hls_product_categories where image = p_url),
    'products', (select count(*) from public.hls_products where p_url = any(images) or p_url = any(spec_images)),
    'locations', (select count(*) from public.hls_locations where image = p_url)
  ) else null end;
$$;

