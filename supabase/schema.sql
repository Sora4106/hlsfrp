-- Create a PUBLIC Storage bucket named hls-site-assets in the Supabase dashboard.
-- Storage file operations must use the Storage API; these policies restrict
-- upload, replacement and deletion to users listed in public.hls_admins.
drop policy if exists "hls_storage_admin_insert" on storage.objects;
create policy "hls_storage_admin_insert" on storage.objects
for insert to authenticated
with check (bucket_id = 'hls-site-assets' and public.hls_is_admin());
drop policy if exists "hls_storage_admin_update" on storage.objects;
create policy "hls_storage_admin_update" on storage.objects
for update to authenticated
using (bucket_id = 'hls-site-assets' and public.hls_is_admin())
with check (bucket_id = 'hls-site-assets' and public.hls_is_admin());
drop policy if exists "hls_storage_admin_delete" on storage.objects;
create policy "hls_storage_admin_delete" on storage.objects
for delete to authenticated
using (bucket_id = 'hls-site-assets' and public.hls_is_admin());

